import { readFile, writeFile } from 'node:fs/promises';
const base = new URL('../packages/app/src/styles/', import.meta.url);
const read = async name => JSON.parse(await readFile(new URL(name, base), 'utf8'));
const tokens = await read('tokens.json');
// The dark look redefines some of the same tokens and adds none; a name it does not share would be a typo.
const dark = await read('tokens.dark.json');
for (const key of Object.keys(dark)) if (!(key in tokens)) throw new Error(`tokens.dark.json: ${key} is not a token in tokens.json`);
const block = (selector, values, indent = '') => `${indent}${selector} {\n${Object.entries(values).map(([key, value]) => `${indent}  --cc-${key}: ${value};`).join('\n')}\n${indent}}\n`;
const outputs = {
  // Dark follows the device unless someone has chosen for themselves (data-theme, set by app/theme.ts).
  'tokens.css': `/* Generated by scripts/generate-tokens.mjs. Edit tokens.json and tokens.dark.json. */\n${block(':root', tokens)}@media (prefers-color-scheme: dark) {\n${block(':root:not([data-theme="light"])', dark, '  ')}}\n${block(':root[data-theme="dark"]', dark)}`,
  'tokens.ts': `// Generated by scripts/generate-tokens.mjs. Edit tokens.json.\nexport const tokens = ${JSON.stringify(tokens, null, 2)} as const;\n`,
};
for (const [name, content] of Object.entries(outputs)) {
  if (process.argv.includes('--check')) {
    if (await readFile(new URL(name, base), 'utf8') !== content) throw new Error(`Stale design tokens: ${name}`);
  } else await writeFile(new URL(name, base), content);
}
